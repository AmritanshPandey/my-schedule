import { useEffect, useMemo, useState } from 'react';
import { Pressable, View } from 'react-native';
import type { Milestone, ProgressTracker, GoalDirection } from '@planr/core/lib/scheduleTypes';
import {
  calculateMilestoneEndDate,
  calculateNextMilestoneStart,
  normalizeDurationToDays,
  cascadeMilestoneDates,
  type DurationType,
} from '@planr/core/lib/roadmapDates';
import { formatDate, todayISO } from '@planr/core/lib/dateUtils';
import { uid } from '@planr/core/lib/id';
import BottomSheet from '../ui/BottomSheet';
import SheetHeader from '../ui/SheetHeader';
import Button from '../ui/Button';
import Input from '../ui/Input';
import DateInput from '../ui/DateInput';
import SegmentedControl from '../ui/SegmentedControl';
import { typography } from '../ui/Typography';
import { Text } from '../ui/Text';

export interface MilestoneSaveData {
  id?: string;   // pre-generated by caller when the ID is needed before creation
  title: string;
  description?: string;
  notes?: string;
  startDate: string;
  plannedDurationDays: number;
  plannedEndDate: string;
  actualCompletedDate?: string;
  status: Milestone['status'];
  linkedActivities: string[];
  linkedTrackers: string[];
  sortOrder: number;
  targetDate?: string;
  estimatedDays?: number;
  linkedTrackerId?: string;
  completionStatus?: 'pending' | 'completed';
  completedDate?: string;
  /**
   * A brand-new tracker to create and link as this milestone's success
   * metric, when the draft defined one instead of picking an existing
   * tracker. The caller (PlanDetailView's handleMilestoneSave) creates it via
   * the same onAddTracker path the title-detection suggestion already uses,
   * then saves the milestone with `linkedTrackers: [newTracker.id]` (already
   * set on this same MilestoneSaveData) pointing at it.
   */
  newTracker?: {
    id: string;
    title: string;
    unit: string;
    goalDirection: GoalDirection;
    goalValue?: number;
    startingValue?: number;
  };
}

interface MilestoneSheetProps {
  mode: 'create' | 'edit';
  milestone?: Milestone | null;
  milestones: Milestone[];
  /** The plan's existing trackers — offered as a pick for this milestone's
   *  success metric, alongside defining a brand-new one. */
  trackers: ProgressTracker[];
  planStartDate?: string;
  isOpen: boolean;
  onClose: () => void;
  onSave: (data: MilestoneSaveData) => void;
}

interface DraftState {
  title: string;
  description: string;
  notes: string;
  startDate: string;
  durationValue: string;
  durationType: DurationType;
  // Success metric — only editable while the milestone has no tracker linked
  // yet (a linked one is managed from the milestone's own detail view, so
  // this never becomes a second, conflicting place to unlink it).
  metricMode: 'none' | 'existing' | 'new';
  existingTrackerId: string;
  newTrackerTitle: string;
  newTrackerUnit: string;
  newTrackerGoalDirection: GoalDirection;
  newTrackerGoalValue: string;
  newTrackerStartingValue: string;
}

const DURATION_TYPES: Array<{ value: DurationType; label: string }> = [
  { value: 'days', label: 'Days' },
  { value: 'weeks', label: 'Weeks' },
  { value: 'months', label: 'Months' },
];

function daysBetween(startDate: string, endDate: string): number {
  const start = new Date(`${startDate}T00:00:00`).getTime();
  const end = new Date(`${endDate}T00:00:00`).getTime();
  return Math.round((end - start) / 86_400_000);
}

function inferDurationDraft(days: number): Pick<DraftState, 'durationValue' | 'durationType'> {
  if (days % 30 === 0) return { durationValue: String(days / 30), durationType: 'months' };
  if (days % 7 === 0) return { durationValue: String(days / 7), durationType: 'weeks' };
  return { durationValue: String(days), durationType: 'days' };
}

function defaultStartDate(
  mode: 'create' | 'edit',
  milestone: Milestone | null | undefined,
  milestones: Milestone[],
  planStartDate?: string
): string {
  if (mode === 'edit' && milestone) return milestone.startDate;
  const ordered = [...milestones].sort((a, b) => a.sortOrder - b.sortOrder);
  const last = ordered[ordered.length - 1];
  if (last) return calculateNextMilestoneStart(last.plannedEndDate);
  return planStartDate || todayISO();
}

function emptyDraft(startDate: string): DraftState {
  return {
    title: '',
    description: '',
    notes: '',
    startDate,
    durationValue: '7',
    durationType: 'days',
    metricMode: 'none',
    existingTrackerId: '',
    newTrackerTitle: '',
    newTrackerUnit: '',
    newTrackerGoalDirection: 'increase_good',
    newTrackerGoalValue: '',
    newTrackerStartingValue: '',
  };
}

function milestoneToDraft(milestone: Milestone): DraftState {
  const duration = inferDurationDraft(milestone.plannedDurationDays);
  const linkedTrackerId = milestone.linkedTrackers?.[0];
  return {
    title: milestone.title,
    description: milestone.description ?? '',
    notes: milestone.notes ?? '',
    startDate: milestone.startDate,
    durationValue: duration.durationValue,
    durationType: duration.durationType,
    metricMode: linkedTrackerId ? 'existing' : 'none',
    existingTrackerId: linkedTrackerId ?? '',
    newTrackerTitle: '',
    newTrackerUnit: '',
    newTrackerGoalDirection: 'increase_good',
    newTrackerGoalValue: '',
    newTrackerStartingValue: '',
  };
}

const DIRECTION_OPTIONS = [
  { value: 'increase_good', label: 'Increase ↑' },
  { value: 'decrease_good', label: 'Decrease ↓' },
] as const satisfies readonly { value: GoalDirection; label: string }[];

function Chip({ active, label, onPress, tone = 'ink' }: { active: boolean; label: string; onPress: () => void; tone?: 'ink' | 'green' }) {
  const on = tone === 'green' ? 'bg-emerald-600 dark:bg-emerald-500' : 'bg-neutral-900 dark:bg-white';
  const onText = tone === 'green' ? 'text-white dark:text-neutral-950' : 'text-white dark:text-neutral-900';
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityState={{ selected: active }}
      onPress={onPress}
      className={`rounded-full px-3 py-1.5 ${active ? on : 'border border-neutral-200 dark:border-white/10'}`}
    >
      <Text className={`text-[12.5px] font-semibold ${active ? onText : 'text-neutral-600 dark:text-neutral-300'}`}>{label}</Text>
    </Pressable>
  );
}

/**
 * Native port of components/plan/MilestoneSheet.tsx — add/edit a roadmap
 * milestone: dates, duration (with the cascade preview), and the success
 * metric (none / existing tracker / define a new one).
 */
export default function MilestoneSheet({
  mode,
  milestone,
  milestones,
  trackers,
  planStartDate,
  isOpen,
  onClose,
  onSave,
}: MilestoneSheetProps) {
  const [draft, setDraft] = useState<DraftState>(() => emptyDraft(defaultStartDate(mode, milestone, milestones, planStartDate)));

  const orderedMilestones = useMemo(() => [...milestones].sort((a, b) => a.sortOrder - b.sortOrder), [milestones]);
  const canEditStartDate = mode === 'edit' || orderedMilestones.length === 0;

  useEffect(() => {
    if (!isOpen) return;
    const startDate = defaultStartDate(mode, milestone, milestones, planStartDate);
    setDraft(mode === 'edit' && milestone ? milestoneToDraft(milestone) : emptyDraft(startDate));
  }, [isOpen, mode, milestone, milestones, planStartDate]);

  const durationValue = Number(draft.durationValue);
  const plannedDurationDays = normalizeDurationToDays(durationValue, draft.durationType);
  const plannedEndDate = draft.startDate ? calculateMilestoneEndDate(draft.startDate, plannedDurationDays) : '';

  const preview = useMemo(() => {
    if (mode !== 'edit' || !milestone || !draft.startDate || !plannedEndDate) return null;
    const recalculated = cascadeMilestoneDates(orderedMilestones, milestone.id, {
      startDate: draft.startDate,
      plannedDurationDays,
      plannedEndDate,
    });
    const originalFuture = orderedMilestones.filter((item) => item.sortOrder > milestone.sortOrder);
    const recalculatedFuture = recalculated.filter((item) => item.sortOrder > milestone.sortOrder);
    const firstOriginal = originalFuture[0];
    const firstRecalculated = recalculatedFuture[0];
    const shiftDays =
      firstOriginal && firstRecalculated ? daysBetween(firstOriginal.startDate, firstRecalculated.startDate) : plannedDurationDays - milestone.plannedDurationDays;
    return { count: originalFuture.length, shiftDays };
  }, [draft.startDate, milestone, mode, orderedMilestones, plannedDurationDays, plannedEndDate]);

  const newTrackerTitle = draft.newTrackerTitle.trim();
  const willCreateNewTracker = draft.metricMode === 'new' && newTrackerTitle.length > 0;

  function handleSave() {
    const title = draft.title.trim();
    if (!title || !draft.startDate || !plannedEndDate) return;
    const status = milestone?.status === 'completed' ? 'completed' : 'upcoming';

    let linkedTrackers = milestone?.linkedTrackers ?? [];
    let newTracker: MilestoneSaveData['newTracker'];
    if (willCreateNewTracker) {
      const goalValue = draft.newTrackerGoalValue.trim() ? Number(draft.newTrackerGoalValue) : undefined;
      const startingValue = draft.newTrackerStartingValue.trim() ? Number(draft.newTrackerStartingValue) : undefined;
      const newTrackerId = uid();
      newTracker = {
        id: newTrackerId,
        title: newTrackerTitle,
        unit: draft.newTrackerUnit.trim(),
        goalDirection: draft.newTrackerGoalDirection,
        goalValue: Number.isFinite(goalValue) ? goalValue : undefined,
        startingValue: Number.isFinite(startingValue) ? startingValue : undefined,
      };
      linkedTrackers = [newTrackerId];
    } else if (draft.metricMode === 'existing' && draft.existingTrackerId) {
      linkedTrackers = [draft.existingTrackerId];
    }

    onSave({
      title,
      description: draft.description.trim() || undefined,
      notes: draft.notes.trim() || undefined,
      startDate: draft.startDate,
      plannedDurationDays,
      plannedEndDate,
      actualCompletedDate: milestone?.actualCompletedDate,
      status,
      linkedActivities: milestone?.linkedActivities ?? [],
      linkedTrackers,
      newTracker,
      sortOrder: milestone?.sortOrder ?? orderedMilestones.length,
      targetDate: plannedEndDate,
      estimatedDays: plannedDurationDays,
      linkedTrackerId: linkedTrackers[0],
      completionStatus: status === 'completed' ? 'completed' : 'pending',
      completedDate: milestone?.actualCompletedDate,
    });
    onClose();
  }

  const eyebrow = mode === 'edit' ? 'Edit' : 'New';
  const title = mode === 'edit' ? 'Edit milestone' : 'Add milestone';
  const canSave = !!draft.title.trim() && !!draft.startDate && plannedDurationDays > 0;
  const alreadyLinkedTracker = milestone?.linkedTrackers?.[0] ? trackers.find((t) => t.id === milestone.linkedTrackers[0]) ?? null : null;

  return (
    <BottomSheet open={isOpen} onClose={onClose}>
      <View className="gap-4 p-5 pb-8">
        <SheetHeader eyebrow={eyebrow} title={title} onClose={onClose} />

        <View className="gap-3">
          <Input
            label="Title"
            value={draft.title}
            onChangeText={(v) => setDraft((d) => ({ ...d, title: v }))}
            placeholder="e.g. Build Running Habit"
            autoFocus
            returnKeyType="done"
            onSubmitEditing={() => {
              if (canSave) handleSave();
            }}
          />
          <Input label="Description (optional)" value={draft.description} onChangeText={(v) => setDraft((d) => ({ ...d, description: v }))} placeholder="Brief description..." />
          <Input label="Notes (optional)" value={draft.notes} onChangeText={(v) => setDraft((d) => ({ ...d, notes: v }))} placeholder="Any additional notes..." />

          <DateInput label="Start date" value={draft.startDate} disabled={!canEditStartDate} onChange={(v) => setDraft((d) => ({ ...d, startDate: v }))} />

          <View>
            <Text className={`mb-1.5 ${typography.eyebrow}`}>Duration</Text>
            <View className="gap-2">
              <Input
                keyboardType="number-pad"
                value={draft.durationValue}
                onChangeText={(v) => setDraft((d) => ({ ...d, durationValue: v }))}
                placeholder="14"
                accessibilityLabel="Duration"
              />
              <SegmentedControl
                ariaLabel="Duration unit"
                options={DURATION_TYPES}
                value={draft.durationType}
                onChange={(v) => setDraft((d) => ({ ...d, durationType: v }))}
              />
            </View>
          </View>

          <View className="rounded-2xl border border-neutral-200 bg-neutral-50 px-4 py-3 dark:border-white/10 dark:bg-white/[0.04]">
            <Text className={typography.eyebrow}>Calculated end</Text>
            <Text className="mt-1 text-[16px] font-bold text-neutral-900 dark:text-white">
              {draft.startDate && plannedEndDate ? `${formatDate(draft.startDate)} - ${formatDate(plannedEndDate)}` : 'Set a start date'}
            </Text>
            <Text className="mt-0.5 text-[12px] font-medium text-neutral-500 dark:text-neutral-400">
              {plannedDurationDays} {plannedDurationDays === 1 ? 'day' : 'days'}
            </Text>
          </View>

          {preview && preview.count > 0 && preview.shiftDays !== 0 && (
            <View className="rounded-2xl border border-amber-200 bg-amber-50 px-4 py-3 dark:border-amber-500/20 dark:bg-amber-500/10">
              <Text className="text-[12px] font-semibold text-amber-700 dark:text-amber-300">
                This change will shift {preview.count} future milestone{preview.count === 1 ? '' : 's'} by {preview.shiftDays > 0 ? '+' : ''}
                {preview.shiftDays} days.
              </Text>
            </View>
          )}

          {alreadyLinkedTracker ? (
            <View className="rounded-2xl border border-neutral-200 bg-neutral-50 px-4 py-3 dark:border-white/10 dark:bg-white/[0.04]">
              <Text className={typography.eyebrow}>Success metric</Text>
              <Text className="mt-1 text-[14px] font-semibold text-neutral-800 dark:text-neutral-100">
                {alreadyLinkedTracker.title}
                {alreadyLinkedTracker.unit ? ` (${alreadyLinkedTracker.unit})` : ''}
              </Text>
              <Text className="mt-0.5 text-[12px] text-neutral-500 dark:text-neutral-400">Manage this from the milestone's detail view.</Text>
            </View>
          ) : (
            <View>
              <Text className={`mb-1.5 ${typography.eyebrow}`}>Success metric (optional)</Text>
              <View className="mb-2 flex-row flex-wrap gap-1.5">
                {(['none', ...(trackers.length > 0 ? ['existing'] : []), 'new'] as DraftState['metricMode'][]).map((metricMode) => (
                  <Chip
                    key={metricMode}
                    active={draft.metricMode === metricMode}
                    label={metricMode === 'none' ? 'None' : metricMode === 'existing' ? 'Existing tracker' : 'Define new'}
                    onPress={() =>
                      setDraft((d) => ({
                        ...d,
                        metricMode,
                        existingTrackerId: metricMode === 'existing' && !d.existingTrackerId ? trackers[0]?.id ?? '' : d.existingTrackerId,
                      }))
                    }
                  />
                ))}
              </View>

              {draft.metricMode === 'existing' && trackers.length > 0 && (
                <View className="flex-row flex-wrap gap-1.5">
                  {trackers.map((t) => (
                    <Chip
                      key={t.id}
                      tone="green"
                      active={draft.existingTrackerId === t.id}
                      label={`${t.title}${t.unit ? ` (${t.unit})` : ''}`}
                      onPress={() => setDraft((d) => ({ ...d, existingTrackerId: t.id }))}
                    />
                  ))}
                </View>
              )}

              {draft.metricMode === 'new' && (
                <View className="gap-2.5 rounded-2xl border border-neutral-200 bg-neutral-50 p-3 dark:border-white/10 dark:bg-white/[0.04]">
                  <Input label="Metric title" value={draft.newTrackerTitle} onChangeText={(v) => setDraft((d) => ({ ...d, newTrackerTitle: v }))} placeholder="e.g. Weight" />
                  <Input label="Unit" value={draft.newTrackerUnit} onChangeText={(v) => setDraft((d) => ({ ...d, newTrackerUnit: v }))} placeholder="kg" />
                  <View>
                    <Text className={`mb-1.5 ${typography.eyebrow}`}>Direction</Text>
                    <SegmentedControl
                      ariaLabel="Direction"
                      options={DIRECTION_OPTIONS}
                      value={draft.newTrackerGoalDirection}
                      onChange={(v) => setDraft((d) => ({ ...d, newTrackerGoalDirection: v }))}
                    />
                  </View>
                  <View className="flex-row gap-2">
                    <View className="flex-1">
                      <Input
                        label="Target value"
                        keyboardType="decimal-pad"
                        value={draft.newTrackerGoalValue}
                        onChangeText={(v) => setDraft((d) => ({ ...d, newTrackerGoalValue: v }))}
                        placeholder="75"
                      />
                    </View>
                    <View className="flex-1">
                      <Input
                        label="Starting value (optional)"
                        keyboardType="decimal-pad"
                        value={draft.newTrackerStartingValue}
                        onChangeText={(v) => setDraft((d) => ({ ...d, newTrackerStartingValue: v }))}
                        placeholder="82"
                      />
                    </View>
                  </View>
                </View>
              )}
            </View>
          )}
        </View>

        <Button fullWidth onPress={handleSave} disabled={!canSave}>
          {mode === 'edit' ? 'Save changes' : 'Add milestone'}
        </Button>
      </View>
    </BottomSheet>
  );
}
