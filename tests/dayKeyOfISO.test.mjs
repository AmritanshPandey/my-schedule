import test from "node:test";
import assert from "node:assert/strict";
import { registerHooks } from "node:module";

function resolveWithTsFallback(url, context, nextResolve) {
  try {
    return nextResolve(url, context);
  } catch {
    try {
      return nextResolve(`${url}.ts`, context);
    } catch {
      return nextResolve(`${url}.tsx`, context);
    }
  }
}

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier.startsWith("@/")) {
      const url = new URL(`../${specifier.slice(2)}`, import.meta.url).href;
      return resolveWithTsFallback(url, context, nextResolve);
    }
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if ((specifier.startsWith("./") || specifier.startsWith("../")) && context.parentURL) {
        const url = new URL(specifier, context.parentURL).href;
        try {
          return nextResolve(`${url}.ts`, context);
        } catch {
          return nextResolve(`${url}.tsx`, context);
        }
      }
      throw error;
    }
  },
});

const { dayKeyOfISO, DAYS } = await import("@/packages/core/lib/scheduleConstants.ts");

test("a date maps to its weekday bucket", () => {
  assert.equal(dayKeyOfISO("2026-11-27"), "friday");
  assert.equal(dayKeyOfISO("2026-11-29"), "sunday");
  assert.equal(dayKeyOfISO("2026-11-30"), "monday");
});

test("a whole week maps onto DAYS in order", () => {
  const week = ["2026-11-23", "2026-11-24", "2026-11-25", "2026-11-26", "2026-11-27", "2026-11-28", "2026-11-29"];
  assert.deepEqual(week.map(dayKeyOfISO), DAYS);
});
